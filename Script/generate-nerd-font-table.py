#!/usr/bin/env python3
"""Translates Ghostty's generated src/font/nerd_font_tables.zig into
Sources/GhosttyTerminal/Renderer/NerdFontConstraints.swift.

    Script/generate-nerd-font-table.py <ghostty checkout>
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
ghostty = pathlib.Path(sys.argv[1])
commit = re.search(r'^let ghosttyCommit = "(\w+)"$', (root / "Package.swift").read_text(), re.M).group(1)
source = (ghostty / "src/font/nerd_font_tables.zig").read_text()


def array(name):
    match = re.search(r"pub const %s: \[(\d+)\]u16 = \.\{([^}]*)\};" % name, source)
    values = [v.strip() for v in match.group(2).split(",") if v.strip()]
    assert len(values) == int(match.group(1)), name
    return values


stage1 = array("stage1")
stage2 = array("stage2")
body = source[source.index("pub const stage3"):]
body = body[body.index(".{") + 2:]

enum_names = {
    "fit_cover1": "fitCover1",
    "center1": "center1",
}


def swift_value(field, value):
    if value.startswith("."):
        name = value[1:]
        return "." + enum_names.get(name, name)
    return value


entries = []
depth = 0
current = None
for token in re.finditer(r"null|\.\{|\}|\.(\w+) = ([^,\n]+)", body):
    text = token.group(0)
    if text == "null" and depth == 0:
        entries.append(None)
    elif text == ".{":
        depth += 1
        current = []
    elif text == "}":
        if depth == 0:
            break
        depth -= 1
        entries.append(current)
        current = None
    elif current is not None:
        field = re.sub(r"_(\w)", lambda m: m.group(1).upper(), token.group(1))
        field = {"maxXyRatio": "maxXYRatio"}.get(field, field)
        current.append((field, swift_value(field, token.group(2).strip())))

declared = int(re.search(r"pub const stage3: \[(\d+)\]Elem", source).group(1))
assert len(entries) == declared, (len(entries), declared)


def constraint(fields):
    if fields is None:
        return "nil"
    order = ["size", "alignVertical", "alignHorizontal", "padTop", "padLeft", "padRight", "padBottom",
             "relativeWidth", "relativeHeight", "relativeX", "relativeY", "maxXYRatio",
             "maxConstraintWidth", "height"]
    fields = dict(fields)
    unknown = set(fields) - set(order)
    assert not unknown, unknown
    return "Glyph.Constraint(" + ", ".join(f"{k}: {fields[k]}" for k in order if k in fields) + ")"


def wrap(values, indent="        "):
    lines, line = [], []
    for value in values:
        line.append(value)
        if len(line) == 24:
            lines.append(indent + ", ".join(line) + ",")
            line = []
    if line:
        lines.append(indent + ", ".join(line) + ",")
    return "\n".join(lines)


out = f"""// Ported from ghostty src/font/nerd_font_tables.zig @ {commit}
// Ported from ghostty src/font/nerd_font_attributes.zig @ {commit}
// Copyright (c) 2024 Mitchell Hashimoto, Ghostty contributors. MIT License.
//
// Generated by Script/generate-nerd-font-table.py. Do not edit.

/// Nerd Font glyph constraints: a 3-level codepoint lookup with the layout
/// of Ghostty's unicode/lut.zig. Pages without constrained glyphs share
/// stage2 offset 0, and stage3 index 0 is nil.
enum NerdFontConstraints {{
    static func constraint(_ codepoint: UInt32) -> Glyph.Constraint? {{
        let high = Int(codepoint >> 8)
        guard high < stage1.count, stage1[high] != 0 else {{ return nil }}
        return stage3[Int(stage2[Int(stage1[high]) + Int(codepoint & 0xFF)])]
    }}

    private static let stage1: [UInt16] = [
{wrap(stage1)}
    ]

    private static let stage2: [UInt16] = [
{wrap(stage2)}
    ]

    private static let stage3: [Glyph.Constraint?] = [
{chr(10).join("        " + constraint(e) + "," for e in entries)}
    ]
}}
"""
(root / "Sources/GhosttyTerminal/Renderer/NerdFontConstraints.swift").write_text(out)
print(f"stage1={len(stage1)} stage2={len(stage2)} stage3={len(entries)}")
