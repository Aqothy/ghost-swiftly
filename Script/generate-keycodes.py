#!/usr/bin/env python3
"""Translates Ghostty's src/input/keycodes.zig (Chromium's dom_code_data.inc)
into Sources/GhosttyTerminal/Input/KeyCodes.swift.

    Script/generate-keycodes.py <ghostty checkout>
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
ghostty = pathlib.Path(sys.argv[1])
commit = (root / "Script/ghostty-commit").read_text().strip()
source = (ghostty / "src/input/keycodes.zig").read_text()
key_swift = (root / "Sources/GhosttyVT/Key.swift").read_text()
keys = set(re.findall(r"^    case (\w+)$", key_swift, re.M))

rows = re.findall(
    r'\.\{ (0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), "(\w*)" \}',
    source)


def case(code):
    if not code:
        return None
    if code.startswith("Key") and len(code) == 4:
        name = code[3].lower()
    else:
        name = code[0].lower() + code[1:]
    return name if name in keys else None


mac, usb = [], []
for usb_code, _evdev, _xkb, _win, mac_code, code in rows:
    name = case(code)
    if not name:
        continue
    usb_code, mac_code = int(usb_code, 16), int(mac_code, 16)
    if mac_code != 0xFFFF:
        mac.append((mac_code, name))
    # Keyboard/keypad page (0x07) usages, which UIKey.keyCode reports.
    if usb_code >> 16 == 0x07:
        usb.append((usb_code & 0xFFFF, name))

def entries(pairs):
    return "\n".join(f"        0x{code:04X}: .{name}," for code, name in sorted(set(pairs)))

out = f"""// Ported from ghostty src/input/keycodes.zig @ {commit}
// Copyright (c) 2024 Mitchell Hashimoto, Ghostty contributors. MIT License.
// Key data from Chromium's ui/events/keycodes/dom/dom_code_data.inc
// (BSD-style license).
//
// Generated by Script/generate-keycodes.py. Do not edit.

import GhosttyVT

enum KeyCodes {{
    /// macOS virtual keycodes (NSEvent.keyCode).
    static let mac: [UInt16: Key] = [
{entries(mac)}
    ]

    /// USB HID keyboard usages (UIKey.keyCode).
    static let usb: [UInt16: Key] = [
{entries(usb)}
    ]
}}
"""
(root / "Sources/GhosttyTerminal/Input/KeyCodes.swift").write_text(out)
print(f"mac={len(set(mac))} usb={len(set(usb))}")
